      <p class="mb-4">
        Drop a link to your Pure Reactions experience in the description of your main YouTube reaction video. One line is enough:
      </p>
      <div class="my-6 rounded-lg bg-surface p-6 font-mono text-sm text-text-primary">
        🎬 Watch this reaction synced with the original (supports the original creator too): [your Pure Reactions link]
      </div>
      <p class="mb-4">
